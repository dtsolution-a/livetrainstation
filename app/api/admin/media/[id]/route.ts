import fsp from 'node:fs/promises';
import path from 'node:path';
import * as store from '@/lib/server/store';
import { route, notFound, str } from '@/lib/server/http';
import { UPLOAD_DIR } from '@/lib/server/config';
import { audit } from '@/lib/server/audit';
import type { Media } from '../route';

type P = { id: string };

export const PUT = route<P>({ perm: ['media.write'], maxBodyKb: 8 }, async ({ user, ip, params, json }) => {
  const body = await json<{ alt?: unknown }>();
  const alt = str(body.alt, 200);
  let found = false;
  await store.update<Media[]>('media', (list) => {
    const m = list.find((x) => x.id === params.id);
    if (m) { m.alt = alt; found = true; }
  });
  if (!found) throw notFound('File not found.');
  audit({ user, ip }, 'media.update', params.id);
  return { ok: true };
});

export const DELETE = route<P>({ perm: ['media.delete'] }, async ({ user, ip, params }) => {
  const m = store.get<Media[]>('media').find((x) => x.id === params.id);
  if (!m) throw notFound('File not found.');
  await store.update<Media[]>('media', (list) => list.filter((x) => x.id !== m.id));
  // file name was generated by us (hex + known ext), but resolve defensively anyway
  const target = path.join(UPLOAD_DIR, path.basename(m.file));
  await fsp.unlink(target).catch(() => {});
  audit({ user, ip }, 'media.delete', m.name);
  return { ok: true };
});
